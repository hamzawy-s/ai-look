class WAFType(Enum):
    """WAF vendor classification."""
    CLOUDFLARE = "CLOUDFLARE"
    AWS_WAF = "AWS_WAF"
    AZURE_WAF = "AZURE_WAF"
    GOOGLE_CLOUD_ARMOR = "GOOGLE_CLOUD_ARMOR"
    MODSECURITY = "MODSECURITY"
    IMPERVA = "IMPERVA"
    F5_BIGIP = "F5_BIGIP"
    AKAMAI = "AKAMAI"
    SUCURI = "SUCURI"
    UNKNOWN = "UNKNOWN"
    NONE = "NONE"


@dataclass
class WAFSignature:
    """Signature for detecting a specific WAF."""
    waf_type: WAFType
    header_patterns: List[Signature] = field(default_factory=list)
    body_patterns: List[Signature] = field(default_factory=list)
    status_codes: List[int] = field(default_factory=list)
    confidence_boost: float = 0.0

    def match_headers(self, headers: Dict[str, str]) -> List[Signature]:
        """Check if any header signature matches."""
        matcher = SignatureMatcher(self.header_patterns)
        # Check each header value
        matches = []
        for header_name, header_value in headers.items():
            matched = matcher.match(f"{header_name}: {header_value}")
            matches.extend(matched)
        return matches

    def match_body(self, body: str) -> List[Signature]:
        """Check if any body signature matches."""
        matcher = SignatureMatcher(self.body_patterns)
        return matcher.match(body)

    def match_status(self, status_code: int) -> bool:
        """Check if status code matches."""
        return status_code in self.status_codes if self.status_codes else False


