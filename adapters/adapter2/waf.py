@dataclass
class WAFDetectionResult:
    """Result of WAF detection."""
    waf_type: WAFType
    confidence: float
    matched_signatures: List[Signature]
    evidence_list: List[Evidence]
    detection_method: str  # "header", "body", "status", "mixed"

    @property
    def is_waf_present(self) -> bool:
        return self.waf_type != WAFType.NONE and self.confidence >= 0.5


class WAFDetector(BaseVulnerabilityAdapter):
    """Detect and fingerprint Web Application Firewalls."""

    def __init__(
        self,
        request_engine: Any,
        scope_engine: Any,
        max_requests_per_target: int = 20,  # WAF detection is lightweight
        max_concurrent_requests: int = 3,
        *,
        budget_manager=None,
        scan_id=None,
    ):
        super().__init__(
            request_engine=request_engine,
            scope_engine=scope_engine,
            max_requests_per_target=max_requests_per_target,
            max_concurrent_requests=max_concurrent_requests,
            budget_manager=budget_manager,
            scan_id=scan_id,
        )
        self.signatures = WAF_SIGNATURES

    def _create_waf_probe_requests(self, target_url: str) -> List[TestRequest]:
        """Create probe requests to trigger WAF responses."""
        probes = []

        # 1. Normal request (baseline)
        probes.append(TestRequest(
            url=target_url,
            method="GET",
            headers={"User-Agent": "Mozilla/5.0"},
        ))

        # 2-3. Harmless marker requests can reveal vendor headers/challenges
        # without attempting SQL, script execution, file access, or traversal.
        probes.append(TestRequest(
            url=target_url,
            method="GET",
            params={"ailook_probe": "baseline-marker"},
            headers={"User-Agent": "Mozilla/5.0"},
        ))
        probes.append(TestRequest(
            url=target_url,
            method="GET",
            headers={"User-Agent": "Mozilla/5.0", "X-AI-Look-Probe": "baseline-marker"},
        ))

        return probes

    def _analyze_response(
        self,
        request: TestRequest,
        response: TestResponse,
    ) -> Dict[WAFType, List[Signature]]:
        """Analyze response for WAF signatures."""
        matches: Dict[WAFType, List[Signature]] = {}

        for waf_sig in self.signatures:
            sig_matches = []

            # Check headers
            header_matches = waf_sig.match_headers(response.headers)
            sig_matches.extend(header_matches)

            # Check body
            body_matches = waf_sig.match_body(response.body)
            sig_matches.extend(body_matches)

            if sig_matches:
                matches[waf_sig.waf_type] = sig_matches

        return matches

    def _calculate_waf_confidence(
        self,
        waf_type: WAFType,
        matches: List[Signature],
        response: TestResponse,
    ) -> float:
        """Calculate confidence score for WAF detection."""
        confidence = 0.0

        # A 403 is contextual evidence only; a vendor or block signature
        # must independently match before a WAF is identified.
        confidence += 0.55 if matches else 0.0
        if response.status_code in [403, 406, 429, 503]:
            confidence += 0.15

        # Boost from specific WAF signature
        for waf_sig in self.signatures:
            if waf_sig.waf_type == waf_type:
                confidence += waf_sig.confidence_boost
                break

        return min(confidence, 1.0)

    def _determine_detection_method(self, matches: List[Signature]) -> str:
        """Determine how WAF was detected."""
        has_header = any("header" in sig.description.lower() for sig in matches)
        has_body = any("page" in sig.description.lower() or "block" in sig.description.lower() for sig in matches)
        has_status = any("status" in sig.description.lower() for sig in matches)

        if has_header and has_body:
            return "mixed"
        elif has_header:
            return "header"
        elif has_body:
            return "body"
        elif has_status:
            return "status"
        return "unknown"

    async def detect(self, target_url: str) -> WAFDetectionResult:
        """Detect WAF on target URL."""
        # Preserve the direct detect() contract used by existing callers. Every
        # outbound probe still passes through execute_request's scope gate.
        if not self._is_authorized(target_url, "GET"):
            raise ValueError(f"Target {target_url} is not in scope")
        # Create probe requests
        probes = self._create_waf_probe_requests(target_url)

        # Collect responses
        responses: List[Tuple[TestRequest, TestResponse]] = []
        for probe in probes:
            try:
                outcome = await self.execute_request(probe)
                if outcome.response is not None:
                    responses.append((probe, outcome.response))
                if not outcome.ok:
                    self._capture_attempt(outcome)
            except Exception:
                continue

        if not responses:
            return WAFDetectionResult(
                waf_type=WAFType.UNKNOWN,
                confidence=0.0,
                matched_signatures=[],
                evidence_list=[],
                detection_method="error",
            )

        # Aggregate matches across all responses
        all_matches: Dict[WAFType, List[Signature]] = {}
        all_evidence: List[Evidence] = []

        for request, response in responses:
            matches = self._analyze_response(request, response)

            for waf_type, sig_matches in matches.items():
                if waf_type not in all_matches:
                    all_matches[waf_type] = []
                all_matches[waf_type].extend(sig_matches)

                # Create evidence for each match
                for sig in sig_matches:
                    evidence = Evidence.from_request_response(
                        request=request,
                        response=response,
                        signature=sig.description,
                    )
                    all_evidence.append(evidence)

        # Determine most likely WAF
        if not all_matches:
            return WAFDetectionResult(
                waf_type=WAFType.NONE,
                confidence=1.0,
                matched_signatures=[],
                evidence_list=[],
                detection_method="none",
            )

        # Pick WAF with most matches
        best_waf = max(all_matches.keys(), key=lambda w: len(all_matches[w]))
        best_matches = all_matches[best_waf]

        # Calculate confidence
        confidence = self._calculate_waf_confidence(
            best_waf,
            best_matches,
            responses[0][1],  # Use first response for calculation
        )

        # Determine detection method
        detection_method = self._determine_detection_method(best_matches)

        return WAFDetectionResult(
            waf_type=best_waf,
            confidence=confidence,
            matched_signatures=best_matches,
            evidence_list=all_evidence,
            detection_method=detection_method,
        )

    def create_finding(self, result: WAFDetectionResult, target_url: str) -> Optional[Finding]:
        """Create Finding from WAF detection result."""
        if not result.is_waf_present:
            return None

        # Determine severity based on WAF type
        severity_map = {
            WAFType.CLOUDFLARE: Severity.INFO,
            WAFType.AWS_WAF: Severity.INFO,
            WAFType.AZURE_WAF: Severity.INFO,
            WAFType.MODSECURITY: Severity.INFO,
            WAFType.IMPERVA: Severity.INFO,
            WAFType.F5_BIGIP: Severity.INFO,
            WAFType.AKAMAI: Severity.INFO,
            WAFType.SUCURI: Severity.INFO,
            WAFType.UNKNOWN: Severity.LOW,
        }

        severity = severity_map.get(result.waf_type, Severity.INFO)

        # Format evidence
        evidence_strings = []
        for ev in result.evidence_list[:5]:  # Limit to 5 evidence items
            evidence_strings.append(
                f"[{ev.request_method} {ev.request_url}] "
                f"WAF Signature: {ev.matched_signature}, "
                f"Status: {ev.response_status}"
            )

        return Finding(
            type="WAF_DETECTED",
            target=target_url,
            parameter="",
            method="GET",
            severity=severity,
            confidence=result.confidence,
            source="WAFDetector",
            status=FindingStatus.OPEN,
            evidence=evidence_strings,
            observation_status=ObservationStatus.PRESENT,
            remediation=f"Observed {result.waf_type.name.replace('_', ' ').title()} as defense-in-depth. "
                       "This is an environmental control observation, not an application vulnerability verdict.",
        )

    async def scan(self, target_url: str, parameters: List[str] = None) -> AdapterScanResult:
        """Scan target for WAF presence."""
        # Detect WAF
        result = await self.detect(target_url)

        # Create finding if WAF detected
        finding = self.create_finding(result, target_url)

        return AdapterScanResult(
            findings=[finding] if finding else [], candidates=[],
            coverage_outcome=(TestOutcome.PRESENT if finding else
                              TestOutcome.ABSENT if result.waf_type == WAFType.NONE else TestOutcome.INCONCLUSIVE),
            reason=(f"identified {result.waf_type.value} from {result.detection_method} signals"
                    if finding else "no WAF signature identified; isolated status codes are insufficient"),
            evidence_count=len(result.evidence_list),
        )
